"""Generate committed OpenAPI + feature index for GYMA API docs."""

from __future__ import annotations

from pathlib import Path

import yaml
from django.core.management.base import BaseCommand, CommandError

from core.api_docs import (
    FEATURE_NAMES,
    build_features_index,
    feature_tag_for_path,
    features_dir,
    generate_live_schema,
    openapi_v1_path,
    write_features_index,
)


class Command(BaseCommand):
    help = "Generate docs/openapi/v1.yaml and docs/features/index.json"

    def add_arguments(self, parser):
        parser.add_argument(
            "--check",
            action="store_true",
            help="Validate tags and fail if committed schema/index would change.",
        )

    def handle(self, *args, **options):
        try:
            schema = generate_live_schema()
        except Exception as exc:
            raise CommandError(f"Failed to generate OpenAPI schema: {exc}") from exc

        unknown: set[str] = set()
        untagged_paths: list[str] = []
        for path, methods in (schema.get("paths") or {}).items():
            for method, operation in methods.items():
                if method.startswith("x-") or not isinstance(operation, dict):
                    continue
                tags = operation.get("tags") or []
                if not tags:
                    untagged_paths.append(f"{method.upper()} {path}")
                    continue
                for tag in tags:
                    if tag not in FEATURE_NAMES:
                        unknown.add(tag)
                # Ensure path mapping agrees with published tag.
                derived = feature_tag_for_path(path)
                if tags != [derived]:
                    operation["tags"] = [derived]

        if unknown:
            raise CommandError(f"Unknown feature tags in schema: {sorted(unknown)}")
        if untagged_paths:
            raise CommandError("Operations missing tags:\n  " + "\n  ".join(untagged_paths[:20]))

        target = openapi_v1_path()
        target.parent.mkdir(parents=True, exist_ok=True)
        rendered = yaml.safe_dump(schema, sort_keys=False, allow_unicode=True)
        index = build_features_index(schema)
        index_path = features_dir() / "index.json"
        index_text = __import__("json").dumps(index, indent=2) + "\n"

        if options["check"]:
            problems = []
            if not target.is_file():
                problems.append(f"missing {target}")
            elif target.read_text(encoding="utf-8") != rendered:
                problems.append(f"stale {target} (run make schema)")
            if not index_path.is_file():
                problems.append(f"missing {index_path}")
            elif index_path.read_text(encoding="utf-8") != index_text:
                problems.append(f"stale {index_path} (run make schema)")
            missing_packs = [
                name
                for name in sorted(FEATURE_NAMES)
                if not (features_dir() / f"{name}.md").is_file()
            ]
            if missing_packs:
                problems.append(f"missing feature packs: {', '.join(missing_packs)}")
            if problems:
                raise CommandError("API docs check failed:\n- " + "\n- ".join(problems))
            self.stdout.write(self.style.SUCCESS("API docs are up to date."))
            return

        target.write_text(rendered, encoding="utf-8")
        write_features_index(schema)
        # Keep legacy path as a short pointer for older links.
        legacy = Path(target).parents[1] / "openapi.yaml"
        legacy.write_text(
            "# Deprecated path — use docs/openapi/v1.yaml\n"
            "# Generated by: python manage.py build_api_docs\n" + rendered,
            encoding="utf-8",
        )
        self.stdout.write(self.style.SUCCESS(f"Wrote {target}"))
        self.stdout.write(self.style.SUCCESS(f"Wrote {index_path}"))
